/** Platform logo for real platforms; a plain symbol for Blog / Email / Podcast / Webinar. */
export function ChannelIcon({ channel, className = "h-3.5 w-3.5" }: { channel: string; className?: string }) {
  switch (channel) {
    case "YouTube":   return <Youtube className={className} aria-hidden="true" />
    case "Instagram": return <Instagram className={className} aria-hidden="true" />
    case "LinkedIn":  return <Linkedin className={className} aria-hidden="true" />
    case "TikTok":    return <TikTokLogo className={className} />
    case "Twitter/X": return <XLogo className={className} />
    case "Facebook":  return <FacebookLogo className={className} />
    case "Website":   return <Globe className={className} aria-hidden="true" />
    case "Blog":      return <PenLine className={className} aria-hidden="true" />
    case "Email":     return <Mail className={className} aria-hidden="true" />
    case "Podcast":   return <Mic className={className} aria-hidden="true" />
    case "Webinar":   return <Video className={className} aria-hidden="true" />
    default:          return <Circle className={className} aria-hidden="true" />
  }
}
